/** Advance per character: 5 px glyph + 1 px spacing. */
const ADVANCE = 6;

export function textWidth(text: string, scale: number): number {
  return text.length * ADVANCE * scale - scale;
}

/** Draw white text onto an RGBA PNG. Unknown characters render as blanks. */
export function drawText(png: PNG, text: string, x0: number, y0: number, scale: number): void {
  [...text.toUpperCase()].forEach((ch, idx) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    glyph?.forEach((bits, row) => {
      for (let col = 0; col < 5; col++) {
        if (!((bits >> (4 - col)) & 1)) continue;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const x = x0 + (idx * ADVANCE + col) * scale + dx;
            const y = y0 + row * scale + dy;
            if (x < 0 || y < 0 || x >= png.width || y >= png.height) continue;
            const i = (y * png.width + x) * 4;
            png.data[i] = 255;
            png.data[i + 1] = 255;
            png.data[i + 2] = 255;
            png.data[i + 3] = 255;
          }
        }
      }
    });
  });
}
